import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const GEONAMES_BASE_URL = "https://download.geonames.org/export/dump";
const COUNTRY_INFO_URL = `${GEONAMES_BASE_URL}/countryInfo.txt`;
const ADMIN1_CODES_URL = `${GEONAMES_BASE_URL}/admin1CodesASCII.txt`;
const ADMIN2_CODES_URL = `${GEONAMES_BASE_URL}/admin2Codes.txt`;
// GeoNames retains these dissolved countries as historical rows at the end of
// countryInfo.txt. They must not be offered for new addresses.
const RETIRED_COUNTRY_CODES = new Set(["AN", "CS"]);

async function download(url) {
  const response = await fetch(url, {
    headers: { "User-Agent": "axpo-location-data-generator" },
  });
  if (!response.ok) {
    throw new Error(`Unable to download ${url}: ${response.status} ${response.statusText}`);
  }
  return response.text();
}

function parseCountries(contents) {
  return contents
    .split(/\r?\n/)
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => {
      const columns = line.split("\t");
      return [columns[0], columns[4]?.trim()];
    })
    .filter(([isoCode, name]) =>
      /^[A-Z]{2}$/.test(isoCode) && name && !RETIRED_COUNTRY_CODES.has(isoCode)
    )
    .sort((a, b) => a[1].localeCompare(b[1], "en"));
}

function normalizeSpanishProvinceName(name) {
  return name.replace(/^(?:Province of|Província de|Provincia (?:da|de))\s+/i, "");
}

function parseSubdivisions(admin1Contents, admin2Contents, countryCodes) {
  const subdivisions = new Map();

  for (const line of admin1Contents.split(/\r?\n/)) {
    if (!line) continue;
    const [compoundCode, rawName] = line.split("\t");
    const name = rawName?.trim();
    const separator = compoundCode?.indexOf(".") ?? -1;
    if (separator < 1 || !name) continue;

    const countryCode = compoundCode.slice(0, separator);
    const adminCode = compoundCode.slice(separator + 1);
    if (!countryCodes.has(countryCode) || adminCode === "00" || countryCode === "ES") continue;

    const names = subdivisions.get(countryCode) ?? new Set();
    names.add(name);
    subdivisions.set(countryCode, names);
  }

  // GeoNames models Spain's autonomous communities as ADM1 and its provinces
  // (plus the autonomous cities Ceuta and Melilla) as ADM2.
  const spanishProvinces = new Set();
  for (const line of admin2Contents.split(/\r?\n/)) {
    if (!line.startsWith("ES.")) continue;
    const [, rawName] = line.split("\t");
    const name = rawName?.trim();
    if (name) spanishProvinces.add(normalizeSpanishProvinceName(name));
  }
  subdivisions.set("ES", spanishProvinces);

  return Object.fromEntries(
    [...subdivisions]
      .sort(([a], [b]) => a.localeCompare(b, "en"))
      .map(([countryCode, names]) => [
        countryCode,
        [...names].sort((a, b) => a.localeCompare(b, "en")),
      ]),
  );
}

const [countryInfo, admin1Codes, admin2Codes] = await Promise.all([
  download(COUNTRY_INFO_URL),
  download(ADMIN1_CODES_URL),
  download(ADMIN2_CODES_URL),
]);

const countries = parseCountries(countryInfo);
const subdivisions = parseSubdivisions(
  admin1Codes,
  admin2Codes,
  new Set(countries.map(([isoCode]) => isoCode)),
);

if (countries.length < 240 || Object.keys(subdivisions).length < 200) {
  throw new Error("GeoNames returned an unexpectedly small location dataset");
}
if (subdivisions.ES.length < 50) {
  throw new Error("GeoNames returned an unexpectedly small Spanish province dataset");
}

const output = `// Generated by scripts/generate-location-data.mjs from GeoNames countryInfo.txt, admin1CodesASCII.txt, and admin2Codes.txt.\n` +
  `// GeoNames data is licensed under CC BY 4.0: https://creativecommons.org/licenses/by/4.0/\n` +
  `// Spain uses GeoNames ADM2; other countries use GeoNames ADM1.\n` +
  `export const COUNTRY_ENTRIES = ${JSON.stringify(countries, null, 2)} as const;\n\n` +
  `export const SUBDIVISIONS_BY_COUNTRY: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(subdivisions, null, 2)};\n`;

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
await writeFile(path.join(projectRoot, "src/lib/location-data.generated.ts"), output);
